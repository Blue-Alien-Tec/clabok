// Package render turns an open book into deterministic Markdown files.
//
// Rendering is a pure function of the manifest, the extracted bodies and the book settings. It
// never writes; Sync compares the rendered result with the output directory and writes only when
// asked.
package render

import (
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Blue-Alien-Tec/clabok/internal/asciiui"
	"github.com/Blue-Alien-Tec/clabok/internal/badge"
	"github.com/Blue-Alien-Tec/clabok/internal/lifecycle"
	"github.com/Blue-Alien-Tec/clabok/internal/model"
	"github.com/Blue-Alien-Tec/clabok/internal/prose"
	"github.com/Blue-Alien-Tec/clabok/internal/refs"
	"github.com/Blue-Alien-Tec/clabok/internal/store"
)

// Marker is the first line of every generated file. It protects hand-written files from being
// overwritten and marks generated files for pruning.
const Marker = "<!-- generated by pecia; do not edit -->"

// Error is a render failure with a stable code.
type Error struct {
	Code    string
	Message string
}

// Error returns the human message.
func (err *Error) Error() string { return err.Message }

// ErrorCode returns the stable code for the CLI boundary.
func (err *Error) ErrorCode() string { return err.Code }

func fail(code, format string, args ...any) *Error {
	return &Error{Code: code, Message: fmt.Sprintf(format, args...)}
}

// File is one rendered file, relative to the output directory.
type File struct {
	Path    string
	Content string
}

// Result is the rendered book.
type Result struct {
	Files []File
	Mode  model.OutputMode
}

// Service renders one book.
type Service struct {
	Lifecycle *lifecycle.Lifecycle
	// Overrides maps a generic asciiui widget name to a project-specific label.
	Overrides map[string]string
	// LibraryIndex is the generated library Document Index. It is set only for the library book; it
	// participates in the book's input hash, so a registry change makes the README dirty.
	LibraryIndex []IndexEntry
	// CrossLink resolves an ID in another registered book; nil means only this book is resolvable.
	CrossLink CrossLinkFunc
	// CrossBook resolves another registered book's README.
	CrossBook CrossBookFunc
	// Navigation describes the current book's place in the library. It drives the README and
	// per-file navigation.
	Navigation Navigation
	// ProjectDir holds the repository facts for the badge detectors.
	ProjectDir string
}

// IndexEntry is one row of the library Document Index.
type IndexEntry struct {
	Title string `json:"title"`
	Href  string `json:"href"`
}

// New returns a render service.
func New(life *lifecycle.Lifecycle) *Service {
	return &Service{Lifecycle: life}
}

// bookSource is the render input of one book. It is either the extracted state (open or unsaved) or
// the packed container, chosen without changing the lifecycle state.
type bookSource struct {
	paths        store.BookPaths
	manifest     *model.Manifest
	manifestData []byte
	bodies       map[model.ID]string
	layouts      map[model.ID][]byte
	open         bool
}

// readSource loads the render input. The extracted state wins while the book is extracted; a
// closed book is read from its container. Nothing is written and no book is opened.
func (service *Service) readSource(book model.BookID) (*bookSource, error) {
	paths, err := service.Lifecycle.Paths(book)
	if err != nil {
		return nil, err
	}
	state, err := service.Lifecycle.State(book)
	if err != nil {
		return nil, err
	}
	if state.Extracted {
		source, extractErr := readExtracted(paths)
		if extractErr == nil {
			return source, nil
		}
		if !errors.Is(extractErr, os.ErrNotExist) {
			return nil, extractErr
		}
	}
	return readContainer(paths)
}

func readExtracted(paths store.BookPaths) (*bookSource, error) {
	data, err := os.ReadFile(filepath.Join(paths.Dir, lifecycle.ManifestMember))
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		return nil, fail("render.read-failed", "%v", err)
	}
	manifest, err := model.Decode(data)
	if err != nil {
		return nil, err
	}
	bodies, err := loadBodies(paths)
	if err != nil {
		return nil, err
	}
	layouts, err := loadLayoutsDir(filepath.Join(paths.Dir, "layouts", "asciiui"))
	if err != nil {
		return nil, err
	}
	return &bookSource{
		paths: paths, manifest: manifest, manifestData: data, bodies: bodies, layouts: layouts, open: true,
	}, nil
}

func readContainer(paths store.BookPaths) (*bookSource, error) {
	container, err := store.Load(paths.Container)
	if err != nil {
		return nil, err
	}
	data, ok := container.Read(lifecycle.ManifestMember)
	if !ok {
		return nil, fail("render.manifest-missing",
			"book %q has no %s member", paths.ID, lifecycle.ManifestMember)
	}
	manifest, err := model.Decode(data)
	if err != nil {
		return nil, err
	}
	bodies := map[model.ID]string{}
	layouts := map[model.ID][]byte{}
	for _, name := range container.Names() {
		if strings.HasPrefix(name, "blocks/") && strings.HasSuffix(name, ".md") {
			id, parseErr := model.ParseID(strings.TrimSuffix(strings.TrimPrefix(name, "blocks/"), ".md"))
			if parseErr != nil {
				continue
			}
			if body, exists := container.Text(name); exists {
				bodies[id] = body
			}
			continue
		}
		if layoutID, layoutOK := layoutMemberID(name); layoutOK {
			if spec, exists := container.Read(name); exists {
				layouts[layoutID] = spec
			}
		}
	}
	return &bookSource{
		paths: paths, manifest: manifest, manifestData: data, bodies: bodies, layouts: layouts, open: false,
	}, nil
}

func loadLayoutsDir(directory string) (map[model.ID][]byte, error) {
	layouts := map[model.ID][]byte{}
	entries, err := os.ReadDir(directory)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return layouts, nil
		}
		return nil, fail("render.read-failed", "%v", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".asciiui") {
			continue
		}
		id, parseErr := model.ParseID(strings.TrimSuffix(entry.Name(), ".asciiui"))
		if parseErr != nil {
			continue
		}
		data, readErr := os.ReadFile(filepath.Join(directory, entry.Name()))
		if readErr != nil {
			return nil, fail("render.read-failed", "%v", readErr)
		}
		layouts[id] = data
	}
	return layouts, nil
}

func layoutMemberID(name string) (model.ID, bool) {
	prefix := "layouts/asciiui/"
	if !strings.HasPrefix(name, prefix) || !strings.HasSuffix(name, ".asciiui") {
		return model.ZeroID, false
	}
	id, err := model.ParseID(strings.TrimSuffix(strings.TrimPrefix(name, prefix), ".asciiui"))
	if err != nil {
		return model.ZeroID, false
	}
	return id, true
}

// Render builds every file of the book in memory.
func (service *Service) Render(book model.BookID) (Result, error) {
	source, err := service.readSource(book)
	if err != nil {
		return Result{}, err
	}
	return service.render(source)
}

func (service *Service) render(source *bookSource) (Result, error) {
	manifest := source.manifest
	bodies := source.bodies
	// A locked UILayout block is a render anchor: its body is the generated drawing, not prose.
	for _, id := range manifest.PlacedBlocks() {
		if !manifest.IsLocked(id) || manifest.BlockType(id) != "UILayout" {
			continue
		}
		drawing, drawErr := renderAsciiUI(source.layouts[id], id, service.Overrides)
		if drawErr != nil {
			return Result{}, drawErr
		}
		// The fence keeps the drawing's spaces and line breaks intact; Markdown would otherwise
		// collapse the lines into one paragraph and turn "- item" lines into lists.
		bodies[id] = "<!-- asciiui:" + id.String() + " -->\n```text\n" + drawing +
			"\n```\n<!-- /asciiui:" + id.String() + " -->\n"
	}
	mode := manifest.Settings.Output
	badges := ""
	if service.Navigation.IsLibrary {
		badges = service.badgeMarkdown(manifest)
	}
	var files []File
	var err error
	switch mode {
	case model.OutputChapter:
		files, err = renderChapters(manifest, bodies, service.LibraryIndex, service.CrossLink, service.CrossBook, service.Navigation, badges)
	case model.OutputPart:
		files, err = renderParts(manifest, bodies, service.LibraryIndex, service.CrossLink, service.CrossBook, service.Navigation, badges)
	default:
		files, err = renderMonolith(manifest, bodies, service.LibraryIndex, service.CrossLink, service.CrossBook, service.Navigation, badges)
	}
	if err != nil {
		return Result{}, err
	}
	return Result{Files: files, Mode: mode}, nil
}

// badgeMarkdown renders the resolved badges of the library README. A badge without a value is
// omitted; Check reports it as badge-unresolved.
func (service *Service) badgeMarkdown(manifest *model.Manifest) string {
	values, _ := badge.ResolveAll(service.ProjectDir, manifest.Badges)
	images := make([]string, 0, len(values))
	for _, value := range values {
		image := fmt.Sprintf("![%s: %s](%s)", value.Label, value.Message, badge.BadgeURL(value))
		if value.Link != "" {
			image = "[" + image + "](" + value.Link + ")"
		}
		images = append(images, image)
	}
	return strings.Join(images, " ")
}

func renderAsciiUI(specData []byte, id model.ID, overrides map[string]string) (string, error) {
	if len(specData) == 0 {
		return "", fail("render.missing-layout", "block %s has no asciiui spec", id)
	}
	spec, err := asciiui.Parse(string(specData))
	if err != nil {
		return "", err
	}
	return asciiui.Render(spec, overrides)
}

func loadBodies(paths store.BookPaths) (map[model.ID]string, error) {
	bodies := map[model.ID]string{}
	entries, err := os.ReadDir(paths.BlocksDir)
	if errors.Is(err, os.ErrNotExist) {
		return bodies, nil
	}
	if err != nil {
		return nil, fail("render.read-failed", "%v", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		id, parseErr := model.ParseID(strings.TrimSuffix(entry.Name(), ".md"))
		if parseErr != nil {
			continue
		}
		data, readErr := os.ReadFile(filepath.Join(paths.BlocksDir, entry.Name()))
		if readErr != nil {
			return nil, fail("render.read-failed", "%v", readErr)
		}
		bodies[id] = string(data)
	}
	return bodies, nil
}

// members returns the render input as a member set for the drift hash. Layouts are excluded so an
// open and a closed book hash identically.
func (source *bookSource) members() map[string][]byte {
	members := map[string][]byte{lifecycle.ManifestMember: source.manifestData}
	for id, body := range source.bodies {
		members["blocks/"+id.String()+".md"] = []byte(body)
	}
	return members
}

// Slug derives an anchor or file token from a title. Numbers are never part of it.
func Slug(text string) string { return refs.Anchor(text) }

func uniqueSlug(base string, used map[string]struct{}) string {
	slug := base
	for index := 2; ; index++ {
		if _, exists := used[slug]; !exists {
			used[slug] = struct{}{}
			return slug
		}
		slug = fmt.Sprintf("%s-%d", base, index)
	}
}

func marker(book model.BookID, mode model.OutputMode) string {
	return fmt.Sprintf("%s\n<!-- book %s; mode %s -->\n\n", Marker, string(book), string(mode))
}

// statusBadge returns the shields.io badge for an assigned state, or "" when the book does not
// enable status or the state is unknown. The badge is the structural marker: headings, index cells,
// block markers and the legend all use it, so authors never write status markup.
func statusBadge(manifest *model.Manifest, state string) string {
	if !manifest.StatusEnabled() || state == "" {
		return ""
	}
	status, exists := model.FindStatus(state)
	if !exists {
		return ""
	}
	label := url.PathEscape(status.Label)
	color := status.Color
	if color == "" {
		color = "lightgrey"
	}
	return fmt.Sprintf("![status: %s](https://img.shields.io/badge/status-%s-%s?style=flat-square)",
		status.Label, label, color)
}

// statusLegendMarkdown renders the tool-owned vocabulary as a two-column table.
func statusLegendMarkdown(manifest *model.Manifest) string {
	if !manifest.StatusEnabled() {
		return ""
	}
	var builder strings.Builder
	builder.WriteString("**Status**\n\n")
	builder.WriteString("| Status | Meaning |\n| --- | --- |\n")
	for _, status := range model.Statuses {
		fmt.Fprintf(&builder, "| %s | %s |\n",
			statusBadge(manifest, status.ID), cell(status.Description))
	}
	return strings.TrimRight(builder.String(), "\n")
}

func blockTexts(manifest *model.Manifest, bodies map[model.ID]string, ids []model.ID) []string {
	texts := make([]string, 0, len(ids))
	for _, id := range ids {
		text := bodies[id]
		if badge := statusBadge(manifest, manifest.Meta(id).Status); badge != "" {
			text = badge + "\n\n" + text
		}
		if notes := notesFor(manifest, bodies, model.TargetBlock, id); notes != "" {
			text = joinNonEmpty(text, notes)
		}
		texts = append(texts, text)
	}
	return texts
}

func notesFor(manifest *model.Manifest, bodies map[model.ID]string, kind model.TargetKind, id model.ID) string {
	for _, region := range manifest.Regions {
		if region == nil || region.Kind != model.RegionNotes {
			continue
		}
		if region.Target.Kind != kind || region.Target.ID != id {
			continue
		}
		return joinBlocks(blockTexts(manifest, bodies, region.Blocks))
	}
	return ""
}

func joinBlocks(texts []string) string {
	parts := make([]string, 0, len(texts))
	for _, text := range texts {
		trimmed := strings.TrimRight(text, "\n")
		if strings.TrimSpace(trimmed) == "" {
			continue
		}
		parts = append(parts, trimmed)
	}
	if len(parts) == 0 {
		return ""
	}
	return strings.Join(parts, "\n\n") + "\n"
}

func joinNonEmpty(parts ...string) string {
	sections := make([]string, 0, len(parts))
	for _, part := range parts {
		if strings.TrimSpace(part) != "" {
			sections = append(sections, strings.TrimRight(part, "\n"))
		}
	}
	if len(sections) == 0 {
		return ""
	}
	return strings.Join(sections, "\n\n") + "\n"
}

// numberingMap returns the rendered number of every chapter and subchapter. Numbers exist only in
// the rendered heading; the stored titles stay number-free.
func numberingMap(manifest *model.Manifest) map[model.ID]string {
	numbers := map[model.ID]string{}
	if !manifest.Settings.Numbering.Enabled {
		return numbers
	}
	chapterIndex := 0
	for _, chapter := range manifest.Root.Children {
		if chapter.Kind != model.KindChapter {
			continue
		}
		chapterIndex++
		numbers[chapter.ID] = fmt.Sprintf("%d.", chapterIndex)
		subIndex := 0
		for _, sub := range chapter.Children {
			if sub.Kind != model.KindSubchapter {
				continue
			}
			subIndex++
			numbers[sub.ID] = fmt.Sprintf("%d.%d", chapterIndex, subIndex)
		}
	}
	return numbers
}

func heading(level int, number, title string) string {
	if level < 1 {
		level = 1
	}
	if level > 6 {
		level = 6
	}
	text := title
	if number != "" {
		text = number + " " + title
	}
	return strings.Repeat("#", level) + " " + text
}

// anchorLine emits an explicit anchor, so the link target never depends on the rendered number.
func anchorLine(anchor string) string {
	return `<a id="` + anchor + `"></a>`
}

func nodeSection(manifest *model.Manifest, bodies map[model.ID]string, node *model.Node, level int, layout map[model.ID]LinkTarget, numbers map[model.ID]string) string {
	if node.Kind == model.KindLink {
		return ""
	}
	sections := make([]string, 0, 4)
	if target, ok := layout[node.ID]; ok && target.Anchor != "" {
		sections = append(sections, anchorLine(target.Anchor))
	}
	title := node.Title
	if badge := statusBadge(manifest, node.Status); badge != "" {
		title += " " + badge
	}
	sections = append(sections, heading(level, numbers[node.ID], title))
	if blocks := joinBlocks(blockTexts(manifest, bodies, node.Blocks)); blocks != "" {
		sections = append(sections, blocks)
	}
	if notes := notesFor(manifest, bodies, model.TargetNode, node.ID); notes != "" {
		sections = append(sections, notes)
	}
	return strings.Join(sections, "\n\n")
}

func subtree(manifest *model.Manifest, bodies map[model.ID]string, node *model.Node, level int, layout map[model.ID]LinkTarget, numbers map[model.ID]string) string {
	parts := make([]string, 0)
	if section := nodeSection(manifest, bodies, node, level, layout, numbers); section != "" {
		parts = append(parts, section)
	}
	for _, child := range node.Children {
		if child.Kind == model.KindLink {
			continue
		}
		parts = append(parts, subtree(manifest, bodies, child, level+1, layout, numbers))
	}
	return strings.Join(parts, "\n\n")
}

func footer(manifest *model.Manifest, bodies map[model.ID]string) string {
	for _, region := range manifest.Regions {
		if region == nil || region.Kind != model.RegionFooter {
			continue
		}
		return joinBlocks(blockTexts(manifest, bodies, region.Blocks))
	}
	return ""
}

// entry is one index row.
type entry struct {
	title  string
	part   string
	prose  string
	status string
	href   string
	level  int
}

// plainTitle reduces an inline-Markdown title to the plain text an index, ToC or reference link
// shows. Headings keep their formatting; an entry must not, because a code span inside a link reads
// like a nested link and a Markdown link inside a link is invalid.
func plainTitle(title string) string {
	title = unwrapInlineLinks(title)
	title = strings.ReplaceAll(title, "`", "")
	title = strings.ReplaceAll(title, "**", "")
	title = strings.ReplaceAll(title, "__", "")
	return strings.ReplaceAll(title, "~~", "")
}

// unwrapInlineLinks replaces [text](target) with text and ![alt](target) with alt. A construct that
// does not parse is left untouched.
func unwrapInlineLinks(text string) string {
	var builder strings.Builder
	for index := 0; index < len(text); index++ {
		image := text[index] == '!' && index+1 < len(text) && text[index+1] == '['
		if text[index] != '[' && !image {
			builder.WriteByte(text[index])
			continue
		}
		opening := index
		if image {
			index++
		}
		closing := strings.IndexByte(text[index:], ']')
		if closing < 0 {
			builder.WriteString(text[opening : index+1])
			continue
		}
		closing += index
		if closing+1 >= len(text) || text[closing+1] != '(' {
			builder.WriteString(text[opening : index+1])
			continue
		}
		end := strings.IndexByte(text[closing+2:], ')')
		if end < 0 {
			builder.WriteString(text[opening : index+1])
			continue
		}
		builder.WriteString(text[index+1 : closing])
		index = closing + 2 + end
	}
	return builder.String()
}

func indexEntries(manifest *model.Manifest, bodies map[model.ID]string, href func(node *model.Node) string) []entry {
	entries := make([]entry, 0)
	var walk func(children []*model.Node, level int)
	walk = func(children []*model.Node, level int) {
		if level > manifest.Settings.IndexDepth {
			return
		}
		for _, node := range children {
			if node.Kind == model.KindLink {
				if level == 1 {
					entries = append(entries, entry{
						title: plainTitle(node.Title), part: node.Part,
						prose: proseText(bodies, node.ProseBlock), status: statusBadge(manifest, node.Status),
						href: href(node), level: 1,
					})
				}
				continue
			}
			entries = append(entries, entry{
				title: plainTitle(node.Title), part: node.Part,
				prose: proseText(bodies, node.ProseBlock), status: statusBadge(manifest, node.Status),
				href: href(node), level: level,
			})
			walk(node.Children, level+1)
		}
	}
	walk(manifest.Root.Children, 1)
	return entries
}

// proseText returns the index prose of a node from the referenced block body.
func proseText(bodies map[model.ID]string, block model.ID) string {
	if block.IsZero() {
		return ""
	}
	return strings.TrimSpace(bodies[block])
}

// cell escapes one Markdown table cell. A line break cannot occur in a title or in validated prose,
// but a stray one must never break the table.
func cell(text string) string {
	text = strings.ReplaceAll(text, "|", `\|`)
	text = strings.ReplaceAll(text, "\r\n", " ")
	return strings.ReplaceAll(text, "\n", " ")
}

// indexTableMarkdown renders the index as a table. It is used when a status or index prose column
// exists. The part value starts a new table group, so a part line can never be squeezed into a table
// row.
func indexTableMarkdown(entries []entry, withStatus, withDescription bool) string {
	var builder strings.Builder
	open := false
	lastPart := ""
	writeHeader := func() {
		switch {
		case withStatus && withDescription:
			builder.WriteString("| Document | Status | Description |\n| --- | --- | --- |\n")
		case withStatus:
			builder.WriteString("| Document | Status |\n| --- | --- |\n")
		default:
			builder.WriteString("| Document | Description |\n| --- | --- |\n")
		}
	}
	for _, item := range entries {
		if item.level == 1 && item.part != lastPart {
			if open {
				builder.WriteString("\n")
				open = false
			}
			if item.part != "" {
				fmt.Fprintf(&builder, "**%s**\n\n", cell(plainTitle(item.part)))
			}
			lastPart = item.part
		}
		if !open {
			writeHeader()
			open = true
		}
		indent := strings.Repeat("&emsp;", item.level-1)
		document := indent + cell(item.title)
		if item.href != "" {
			document = indent + "[" + cell(item.title) + "](" + item.href + ")"
		}
		switch {
		case withStatus && withDescription:
			fmt.Fprintf(&builder, "| %s | %s | %s |\n",
				document, cell(item.status), cell(item.prose))
		case withStatus:
			fmt.Fprintf(&builder, "| %s | %s |\n", document, cell(item.status))
		default:
			fmt.Fprintf(&builder, "| %s | %s |\n", document, cell(item.prose))
		}
	}
	return builder.String()
}

// indexMarkdown renders the index as a flat list. It serves the per-file ToC and every book index
// that carries neither prose nor status.
func indexMarkdown(entries []entry) string {
	var builder strings.Builder
	lastPart := ""
	wroteRow := false
	for _, item := range entries {
		if item.level == 1 && item.part != "" && item.part != lastPart {
			if wroteRow {
				builder.WriteString("\n")
			}
			fmt.Fprintf(&builder, "**%s**\n\n", cell(plainTitle(item.part)))
			lastPart = item.part
		}
		indent := strings.Repeat("  ", item.level-1)
		if item.href == "" {
			fmt.Fprintf(&builder, "%s- %s\n", indent, item.title)
		} else {
			fmt.Fprintf(&builder, "%s- [%s](%s)\n", indent, item.title, item.href)
		}
		wroteRow = true
	}
	return builder.String()
}

// bookIndexMarkdown picks the index shape from the data. A table is used when the book enables
// status or an entry carries prose; a plain index stays a list. A column exists only when it has a
// source (status on, prose present). The per-file ToC always uses the list renderer.
func bookIndexMarkdown(entries []entry, statusEnabled bool) string {
	hasProse := false
	for _, item := range entries {
		if item.prose != "" {
			hasProse = true
			break
		}
	}
	if statusEnabled || hasProse {
		return indexTableMarkdown(entries, statusEnabled, hasProse)
	}
	return indexMarkdown(entries)
}

// documentIndexMarkdown renders the library Document Index. It returns "" when no other book is
// registered, so a lone library book does not render an empty section.
func documentIndexMarkdown(entries []IndexEntry) string {
	if len(entries) == 0 {
		return ""
	}
	var builder strings.Builder
	builder.WriteString("| Book |\n| --- |\n")
	for _, item := range entries {
		fmt.Fprintf(&builder, "| [%s](%s) |\n", cell(plainTitle(item.Title)), item.Href)
	}
	return strings.TrimRight(builder.String(), "\n")
}

func renderMonolith(manifest *model.Manifest, bodies map[model.ID]string, index []IndexEntry, cross CrossLinkFunc, crossBook CrossBookFunc, nav Navigation, badges string) ([]File, error) {
	layout := LayoutFor(manifest)
	numbers := numberingMap(manifest)
	entries := indexEntries(manifest, bodies, func(node *model.Node) string {
		if node.Kind == model.KindLink {
			return linkHref(manifest, node, layout, cross, crossBook)
		}
		target, ok := layout[node.ID]
		if !ok || target.Anchor == "" {
			return ""
		}
		return "#" + target.Anchor
	})
	topNav, bottomNav := readmeNav(nav, index, "")
	sections := make([]string, 0, 8)
	if topNav != "" {
		sections = append(sections, topNav)
	}
	if badges != "" {
		sections = append(sections, badges)
	}
	sections = append(sections, heading(1, "", manifest.Root.Title))
	if rootBlocks := joinBlocks(blockTexts(manifest, bodies, manifest.Root.Blocks)); rootBlocks != "" {
		sections = append(sections, rootBlocks)
	}
	if legend := statusLegendMarkdown(manifest); legend != "" {
		sections = append(sections, legend)
	}
	sections = append(sections, "## Index", strings.TrimRight(bookIndexMarkdown(entries, manifest.StatusEnabled()), "\n"))
	if documentIndex := documentIndexMarkdown(index); documentIndex != "" {
		sections = append(sections, "## Document Index", documentIndex)
	}
	for _, child := range manifest.Root.Children {
		if child.Kind == model.KindLink {
			continue
		}
		sections = append(sections, subtree(manifest, bodies, child, 2, layout, numbers))
	}
	if footerText := footer(manifest, bodies); footerText != "" {
		sections = append(sections, footerText)
	}
	if bottomNav != "" {
		if !nav.IsLibrary {
			sections = append(sections, "---")
		}
		sections = append(sections, bottomNav)
	}
	content := marker(manifest.ID, model.OutputMonolith) + strings.Join(sections, "\n\n")
	content = expandRefs(content, "README.md", manifest, layout, cross)
	return []File{{Path: "README.md", Content: strings.TrimRight(content, "\n") + "\n"}}, nil
}

func renderChapters(manifest *model.Manifest, bodies map[model.ID]string, index []IndexEntry, cross CrossLinkFunc, crossBook CrossBookFunc, nav Navigation, badges string) ([]File, error) {
	files := make([]File, 0, len(manifest.Root.Children)+1)
	layout := LayoutFor(manifest)
	numbers := numberingMap(manifest)
	entries := indexEntries(manifest, bodies, func(node *model.Node) string {
		if node.Kind == model.KindLink {
			return linkHref(manifest, node, layout, cross, crossBook)
		}
		target, ok := layout[node.ID]
		if !ok {
			return ""
		}
		return target.Href()
	})
	first := firstDocument(manifest, layout, nil, nil)
	topNav, bottomNav := readmeNav(nav, index, first)
	indexSections := make([]string, 0, 8)
	if topNav != "" {
		indexSections = append(indexSections, topNav)
	}
	if badges != "" {
		indexSections = append(indexSections, badges)
	}
	indexSections = append(indexSections, heading(1, "", manifest.Root.Title))
	if rootBlocks := joinBlocks(blockTexts(manifest, bodies, manifest.Root.Blocks)); rootBlocks != "" {
		indexSections = append(indexSections, rootBlocks)
	}
	if legend := statusLegendMarkdown(manifest); legend != "" {
		indexSections = append(indexSections, legend)
	}
	indexSections = append(indexSections, "## Index", strings.TrimRight(bookIndexMarkdown(entries, manifest.StatusEnabled()), "\n"))
	if documentIndex := documentIndexMarkdown(index); documentIndex != "" {
		indexSections = append(indexSections, "## Document Index", documentIndex)
	}
	if footerText := footer(manifest, bodies); footerText != "" {
		indexSections = append(indexSections, footerText)
	}
	if bottomNav != "" {
		if !nav.IsLibrary {
			indexSections = append(indexSections, "---")
		}
		indexSections = append(indexSections, bottomNav)
	}
	indexContent := marker(manifest.ID, model.OutputChapter) + strings.Join(indexSections, "\n\n")
	indexContent = expandRefs(indexContent, "README.md", manifest, layout, cross)
	files = append(files, File{Path: "README.md", Content: strings.TrimRight(indexContent, "\n") + "\n"})

	for position, chapter := range manifest.Root.Children {
		if chapter.Kind == model.KindLink {
			continue
		}
		file := layout[chapter.ID].File
		previous := neighbouringChapterFile(manifest, layout, position, -1)
		next := neighbouringChapterFile(manifest, layout, position, 1)
		fileNav := chapterNav(previous, next)
		sections := []string{fileNav, "---"}
		if manifest.Settings.TOC.Enabled {
			if toc := chapterTOC(manifest, layout, chapter); toc != "" {
				sections = append(sections, toc)
			}
		}
		sections = append(sections, subtree(manifest, bodies, chapter, 1, layout, numbers))
		sections = append(sections, "---", fileNav)
		content := marker(manifest.ID, model.OutputChapter) + strings.Join(sections, "\n\n")
		content = expandRefs(content, file, manifest, layout, cross)
		files = append(files, File{Path: file, Content: strings.TrimRight(content, "\n") + "\n"})
	}
	return files, nil
}

func renderParts(manifest *model.Manifest, bodies map[model.ID]string, index []IndexEntry, cross CrossLinkFunc, crossBook CrossBookFunc, nav Navigation, badges string) ([]File, error) {
	for _, chapter := range manifest.Root.Children {
		if chapter.Kind == model.KindChapter && strings.TrimSpace(chapter.Part) == "" {
			return nil, fail("render.missing-part", "chapter %q has no part", chapter.Title)
		}
	}
	partFile, fileErr := partFileMap(manifest, true)
	if fileErr != nil {
		return nil, fileErr
	}
	parts := partOrder(manifest)
	layout := LayoutFor(manifest)
	numbers := numberingMap(manifest)
	entries := indexEntries(manifest, bodies, func(node *model.Node) string {
		if node.Kind == model.KindLink {
			return linkHref(manifest, node, layout, cross, crossBook)
		}
		target, ok := layout[node.ID]
		if !ok {
			return ""
		}
		return target.Href()
	})
	first := firstDocument(manifest, layout, parts, partFile)
	topNav, bottomNav := readmeNav(nav, index, first)
	indexSections := make([]string, 0, 8)
	if topNav != "" {
		indexSections = append(indexSections, topNav)
	}
	if badges != "" {
		indexSections = append(indexSections, badges)
	}
	indexSections = append(indexSections, heading(1, "", manifest.Root.Title))
	if rootBlocks := joinBlocks(blockTexts(manifest, bodies, manifest.Root.Blocks)); rootBlocks != "" {
		indexSections = append(indexSections, rootBlocks)
	}
	if legend := statusLegendMarkdown(manifest); legend != "" {
		indexSections = append(indexSections, legend)
	}
	indexSections = append(indexSections, "## Index", strings.TrimRight(bookIndexMarkdown(entries, manifest.StatusEnabled()), "\n"))
	if documentIndex := documentIndexMarkdown(index); documentIndex != "" {
		indexSections = append(indexSections, "## Document Index", documentIndex)
	}
	if footerText := footer(manifest, bodies); footerText != "" {
		indexSections = append(indexSections, footerText)
	}
	if bottomNav != "" {
		if !nav.IsLibrary {
			indexSections = append(indexSections, "---")
		}
		indexSections = append(indexSections, bottomNav)
	}
	indexContent := marker(manifest.ID, model.OutputPart) + strings.Join(indexSections, "\n\n")
	indexContent = expandRefs(indexContent, "README.md", manifest, layout, cross)
	files := []File{{Path: "README.md", Content: strings.TrimRight(indexContent, "\n") + "\n"}}

	for position, part := range parts {
		previous := ""
		if position > 0 {
			previous = partFile[parts[position-1]]
		}
		next := ""
		if position+1 < len(parts) {
			next = partFile[parts[position+1]]
		}
		fileNav := chapterNav(previous, next)
		sections := []string{fileNav, "---"}
		if manifest.Settings.TOC.Enabled {
			if toc := partTOC(manifest, layout, part); toc != "" {
				sections = append(sections, toc)
			}
		}
		sections = append(sections, heading(1, "", part))
		for _, chapter := range manifest.Root.Children {
			if chapter.Kind != model.KindChapter || chapter.Part != part {
				continue
			}
			sections = append(sections, subtree(manifest, bodies, chapter, 2, layout, numbers))
		}
		sections = append(sections, "---", fileNav)
		content := marker(manifest.ID, model.OutputPart) + strings.Join(sections, "\n\n")
		content = expandRefs(content, partFile[part], manifest, layout, cross)
		files = append(files, File{Path: partFile[part], Content: strings.TrimRight(content, "\n") + "\n"})
	}
	return files, nil
}

// neighbouringChapterFile returns the previous or next chapter file, skipping link entries. It
// returns "" at the boundary, so the navigation omits the absent direction.
func neighbouringChapterFile(manifest *model.Manifest, layout map[model.ID]LinkTarget, position, step int) string {
	for index := position + step; index >= 0 && index < len(manifest.Root.Children); index += step {
		target, ok := layout[manifest.Root.Children[index].ID]
		if ok && target.File != "" {
			return target.File
		}
	}
	return ""
}

// chapterTOC lists the subchapters of one chapter file. It returns "" when the chapter has none.
func chapterTOC(manifest *model.Manifest, layout map[model.ID]LinkTarget, chapter *model.Node) string {
	entries := make([]entry, 0)
	for _, child := range chapter.Children {
		if child.Kind == model.KindLink {
			continue
		}
		target, ok := layout[child.ID]
		if !ok || target.Anchor == "" {
			continue
		}
		entries = append(entries, entry{title: plainTitle(child.Title), href: "#" + target.Anchor, level: 1})
	}
	if len(entries) == 0 {
		return ""
	}
	return "**Contents**\n\n" + strings.TrimRight(indexMarkdown(entries), "\n")
}

// partTOC lists the chapters and subchapters of one part file.
func partTOC(manifest *model.Manifest, layout map[model.ID]LinkTarget, part string) string {
	entries := make([]entry, 0)
	for _, chapter := range manifest.Root.Children {
		if chapter.Kind != model.KindChapter || chapter.Part != part {
			continue
		}
		if target, ok := layout[chapter.ID]; ok && target.Anchor != "" {
			entries = append(entries, entry{title: plainTitle(chapter.Title), href: "#" + target.Anchor, level: 1})
		}
		for _, child := range chapter.Children {
			if child.Kind == model.KindLink {
				continue
			}
			if target, ok := layout[child.ID]; ok && target.Anchor != "" {
				entries = append(entries, entry{title: plainTitle(child.Title), href: "#" + target.Anchor, level: 2})
			}
		}
	}
	if len(entries) == 0 {
		return ""
	}
	return "**Contents**\n\n" + strings.TrimRight(indexMarkdown(entries), "\n")
}

// linkHref resolves a link node. A link to another book uses the cross resolver; a local link uses
// the rendered layout. An unresolved link stays plain text and is a dangling finding.
func linkHref(manifest *model.Manifest, node *model.Node, layout map[model.ID]LinkTarget, cross CrossLinkFunc, crossBook CrossBookFunc) string {
	if node.Ref == nil {
		return ""
	}
	targetID := node.Ref.Node
	if targetID.IsZero() {
		targetID = node.Ref.Block
	}
	if node.Ref.Book != "" && node.Ref.Book != manifest.ID {
		if targetID.IsZero() {
			if crossBook != nil {
				if href, ok := crossBook(node.Ref.Book); ok {
					return href
				}
			}
			return ""
		}
		if cross != nil {
			if target, ok := cross(targetID); ok {
				return target.Href
			}
		}
		return ""
	}
	if targetID.IsZero() {
		return ""
	}
	target, ok := layout[targetID]
	if !ok {
		return ""
	}
	if target.File == "README.md" && target.Anchor != "" {
		return "#" + target.Anchor
	}
	return target.Href()
}

// expandRefs turns [[id:N]] into a link to the derived anchor. A local target wins; a target in
// another registered book uses the cross resolver. A dangling reference stays as written and is
// reported by Check.
func expandRefs(content, file string, manifest *model.Manifest, layout map[model.ID]LinkTarget, cross CrossLinkFunc) string {
	return refs.Pattern.ReplaceAllStringFunc(content, func(match string) string {
		groups := refs.Pattern.FindStringSubmatch(match)
		if len(groups) != 2 {
			return match
		}
		id, ok := refs.ParseID(groups[1])
		if !ok {
			return match
		}
		if target, found := refs.Resolve(manifest, id); found {
			link, exists := layout[id]
			if !exists {
				return match
			}
			href := link.Href()
			if link.File == file && link.Anchor != "" {
				href = "#" + link.Anchor
			}
			return "[" + plainTitle(target.Title) + "](" + href + ")"
		}
		if cross != nil {
			if link, found := cross(id); found {
				return "[" + plainTitle(link.Title) + "](" + link.Href + ")"
			}
		}
		return match
	})
}

// SyncOptions controls a sync run.
type SyncOptions struct {
	Check bool
	Write bool
	Prune bool
	Force bool
}

// SyncResult reports a sync run.
type SyncResult struct {
	Mode    model.OutputMode
	Status  store.Status
	Files   []string
	Changed []string
	Foreign []string
	Pruned  []string
	Written bool
}

// Sync compares the rendered book with the output directory and writes on request. The book is read
// from the extracted state when it is open and from the container otherwise; syncing never changes
// the lifecycle state and a check never creates the output directory.
func (service *Service) Sync(book model.BookID, outputDir string, options SyncOptions) (SyncResult, error) {
	source, err := service.readSource(book)
	if err != nil {
		return SyncResult{}, err
	}
	result, err := service.render(source)
	if err != nil {
		return SyncResult{}, err
	}
	rendered := make(map[string]string, len(result.Files))
	for _, file := range result.Files {
		rendered[file.Path] = file.Content
	}
	changed := make([]string, 0)
	foreign := make([]string, 0)
	for _, file := range result.Files {
		target := filepath.Join(outputDir, filepath.FromSlash(file.Path))
		existing, readErr := os.ReadFile(target)
		if errors.Is(readErr, os.ErrNotExist) {
			changed = append(changed, file.Path)
			continue
		}
		if readErr != nil {
			return SyncResult{}, fail("render.read-failed", "%v", readErr)
		}
		if string(existing) == file.Content {
			continue
		}
		if !generatedFor(string(existing), book) {
			foreign = append(foreign, file.Path)
		}
		changed = append(changed, file.Path)
	}
	prune := make([]string, 0)
	entries, readErr := os.ReadDir(outputDir)
	if readErr != nil && !errors.Is(readErr, os.ErrNotExist) {
		return SyncResult{}, fail("render.read-failed", "%v", readErr)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		if _, produced := rendered[entry.Name()]; produced {
			continue
		}
		data, fileErr := os.ReadFile(filepath.Join(outputDir, entry.Name()))
		if fileErr != nil {
			continue
		}
		if generatedFor(string(data), book) {
			prune = append(prune, entry.Name())
		}
	}
	sort.Strings(prune)

	inputHash := store.HashMembers(service.inputMembers(source))
	outputHash := store.HashMembers(contentMap(result.Files))
	previous, _, stateErr := source.paths.ReadState()
	if stateErr != nil {
		return SyncResult{}, stateErr
	}
	status := previous.Compare(inputHash, outputHash)

	resultSync := SyncResult{
		Mode: result.Mode, Status: status, Changed: changed, Foreign: foreign, Pruned: prune,
	}
	for _, file := range result.Files {
		resultSync.Files = append(resultSync.Files, file.Path)
	}
	if options.Check || !options.Write {
		return resultSync, nil
	}
	if len(foreign) > 0 && !options.Force {
		return resultSync, fail("render.foreign-file",
			"%s has no generated marker for book %s; pass --force to overwrite",
			strings.Join(foreign, ", "), book)
	}
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return resultSync, fail("render.write-failed", "%v", err)
	}
	for _, file := range result.Files {
		target := filepath.Join(outputDir, filepath.FromSlash(file.Path))
		if err := store.WriteAtomic(target, []byte(file.Content)); err != nil {
			return resultSync, err
		}
	}
	if options.Prune {
		for _, name := range prune {
			if err := os.Remove(filepath.Join(outputDir, name)); err != nil && !errors.Is(err, os.ErrNotExist) {
				return resultSync, fail("render.write-failed", "%v", err)
			}
		}
	}
	if err := source.paths.WriteState(store.State{InputHash: inputHash, OutputHash: outputHash}); err != nil {
		return resultSync, err
	}
	resultSync.Written = true
	return resultSync, nil
}

// inputMembers is the drift hash input: manifest and bodies, plus the generated library index when
// the book is the library. Layout members are excluded so an open and a closed book hash the same.
func (service *Service) inputMembers(source *bookSource) map[string][]byte {
	members := source.members()
	if len(service.LibraryIndex) > 0 {
		var builder strings.Builder
		for _, entry := range service.LibraryIndex {
			builder.WriteString(entry.Title)
			builder.WriteByte(0)
			builder.WriteString(entry.Href)
			builder.WriteByte('\n')
		}
		members["library-index"] = []byte(builder.String())
	}
	members["nav"] = []byte(fmt.Sprintf("%t|%s", service.Navigation.IsLibrary, service.Navigation.LibraryHref))
	if len(source.manifest.Badges) > 0 {
		values, unresolved := badge.ResolveAll(service.ProjectDir, source.manifest.Badges)
		var builder strings.Builder
		for _, value := range values {
			fmt.Fprintf(&builder, "%s\x00%s\x00%s\x00%s\x00%s\x00%s\n",
				value.ID, value.Label, value.Message, value.Link, value.Source, value.Color)
		}
		for _, item := range unresolved {
			fmt.Fprintf(&builder, "%s\x00%s\n", item.ID, item.Reason)
		}
		members["badges"] = []byte(builder.String())
	}
	return members
}

// generatedFor reports whether a file was generated for this book, so a shared output directory
// cannot be cross-pruned or treated as foreign by another book.
func generatedFor(content string, book model.BookID) bool {
	return strings.HasPrefix(content, Marker+"\n<!-- book "+string(book)+"; mode ")
}

func contentMap(files []File) map[string][]byte {
	members := make(map[string][]byte, len(files))
	for _, file := range files {
		members[file.Path] = []byte(file.Content)
	}
	return members
}

// Finding is one check result.
type Finding struct {
	Code     string `json:"code"`
	Message  string `json:"message"`
	Blocking bool   `json:"blocking"`
}

// Check runs the read-only acceptance checks.
func (service *Service) Check(book model.BookID) ([]Finding, error) {
	source, err := service.readSource(book)
	if err != nil {
		return nil, err
	}
	manifest := source.manifest
	findings := make([]Finding, 0)
	if issues := manifest.Validate(); issues != nil {
		for _, issue := range issues.Issues {
			findings = append(findings, Finding{Code: issue.Code, Message: issue.String(), Blocking: true})
		}
	}
	bodies := source.bodies
	layout := LayoutFor(manifest)
	if len(manifest.Badges) > 0 {
		_, unresolved := badge.ResolveAll(service.ProjectDir, manifest.Badges)
		for _, item := range unresolved {
			findings = append(findings, Finding{
				Code:     "badge-unresolved",
				Message:  fmt.Sprintf("badge %q: %s", item.ID, item.Reason),
				Blocking: false,
			})
		}
	}

	for id, body := range bodies {
		for _, match := range refs.Pattern.FindAllStringSubmatch(body, -1) {
			if len(match) != 2 {
				continue
			}
			refID, ok := refs.ParseID(match[1])
			if !ok {
				continue
			}
			if _, found := refs.Resolve(manifest, refID); found {
				continue
			}
			if service.CrossLink != nil {
				if _, found := service.CrossLink(refID); found {
					continue
				}
			}
			findings = append(findings, Finding{
				Code:     "refs.dangling",
				Message:  fmt.Sprintf("block %s references missing id %s", id, match[1]),
				Blocking: true,
			})
		}
	}
	manifest.Walk(func(node *model.Node, depth int, parent *model.Node) bool {
		if node.Kind == model.KindLink && node.Ref != nil {
			if linkHref(manifest, node, layout, service.CrossLink, service.CrossBook) == "" {
				findings = append(findings, Finding{
					Code:     "refs.dangling",
					Message:  fmt.Sprintf("link %s has no resolvable target", node.ID),
					Blocking: true,
				})
			}
		}
		return true
	})
	for _, id := range manifest.PlacedBlocks() {
		if !manifest.IsLocked(id) || manifest.BlockType(id) != "UILayout" {
			continue
		}
		if _, layoutErr := renderAsciiUI(source.layouts[id], id, service.Overrides); layoutErr != nil {
			code := "render.missing-layout"
			if coded, ok := layoutErr.(interface{ ErrorCode() string }); ok {
				code = coded.ErrorCode()
			}
			findings = append(findings, Finding{Code: code, Message: layoutErr.Error(), Blocking: true})
		}
	}
	for id, body := range bodies {
		if issues := prose.CheckProse(body); len(issues) > 0 {
			findings = append(findings, Finding{
				Code: "body.forbidden-heading",
				Message: fmt.Sprintf("block %s contains a structural heading at line %d",
					id, issues[0].Line),
				Blocking: true,
			})
		}
	}
	if source.open {
		findings = append(findings, Finding{
			Code: "render.open-book", Message: "the book is open; close it for the packed state",
			Blocking: false,
		})
	}
	sort.Slice(findings, func(left, right int) bool { return findings[left].Code < findings[right].Code })
	return findings, nil
}
